-- RPC: apply_stock_delta ----------------------------------------------
-- Concurrency-safe quantity change. Prevents accidental negative stock,
-- updates the batch and writes a matching stock_movements row.
--   add        => p_delta must be positive
--   withdraw   => p_delta must be negative
--   adjustment => signed p_delta (negative allowed only with p_allow_negative)
--   inventory  => used by complete_inventory_session
create or replace function public.apply_stock_delta(
  p_batch_id uuid,
  p_delta integer,
  p_type text,
  p_note text default null,
  p_allow_negative boolean default false
)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_item_id uuid;
  v_lot text;
  v_expiry date;
  v_before integer;
  v_after integer;
begin
  if v_user_id is null then raise exception 'authentication required' using errcode = '42501'; end if;
  if p_delta = 0 then raise exception 'quantity delta cannot be zero' using errcode = '22023'; end if;
  if p_type not in ('add', 'withdraw', 'adjustment', 'inventory') then raise exception 'invalid movement type' using errcode = '22023'; end if;
  if p_type = 'add' and p_delta < 0 then raise exception 'add movement must be positive' using errcode = '22023'; end if;
  if p_type = 'withdraw' and p_delta > 0 then raise exception 'withdraw movement must be negative' using errcode = '22023'; end if;
  if p_allow_negative and p_type <> 'adjustment' then raise exception 'negative stock override is adjustment-only' using errcode = '22023'; end if;

  select item_id, lot_number, expiry_date, current_quantity
    into v_item_id, v_lot, v_expiry, v_before
  from public.batches where id = p_batch_id for update;
  if not found then raise exception 'batch not found' using errcode = 'P0002'; end if;

  v_after := v_before + p_delta;
  if v_after < 0 and not (p_allow_negative and p_type = 'adjustment') then
    raise exception 'insufficient stock' using errcode = '22003';
  end if;

  update public.batches set current_quantity = v_after where id = p_batch_id;

  insert into public.stock_movements(
    item_id, batch_id, type, quantity_delta, quantity_before, quantity_after,
    note, lot_number_snapshot, expiry_date_snapshot, user_id
  ) values (
    v_item_id, p_batch_id, p_type, p_delta, v_before, v_after,
    nullif(btrim(p_note), ''), v_lot, v_expiry, v_user_id
  );

  return v_after;
end;
$$;

-- RPC: complete_inventory_session -------------------------------------
-- Compares expected vs counted, writes inventory movements, updates all
-- quantities atomically, and completes the session. Refuses to complete
-- if stock changed after the inventory snapshot.
create or replace function public.complete_inventory_session(p_session_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_status text;
  v_count record;
  v_current integer;
  v_delta integer;
begin
  if auth.uid() is null then raise exception 'authentication required' using errcode = '42501'; end if;

  select status into v_status from public.inventory_sessions where id = p_session_id for update;
  if not found then raise exception 'inventory session not found' using errcode = 'P0002'; end if;
  if v_status <> 'active' then raise exception 'inventory session is already completed' using errcode = '55000'; end if;

  for v_count in select * from public.inventory_counts where session_id = p_session_id loop
    if v_count.batch_id is null then
      raise exception 'every count must be tied to a batch' using errcode = '22023';
    end if;
    select current_quantity into v_current from public.batches where id = v_count.batch_id for update;
    if v_current <> v_count.expected_quantity then
      raise exception 'stock changed after the inventory snapshot' using errcode = '40001';
    end if;
  end loop;

  for v_count in select * from public.inventory_counts where session_id = p_session_id order by item_id, batch_id loop
    v_delta := v_count.counted_quantity - v_count.expected_quantity;
    if v_delta <> 0 then
      perform public.apply_stock_delta(
        v_count.batch_id, v_delta, 'inventory',
        'Inventory session ' || p_session_id::text, false
      );
    end if;
  end loop;

  update public.inventory_sessions set status = 'completed', completed_at = now() where id = p_session_id;
end;
$$;

-- Signup: create the profile row automatically and copy display_name
-- from the user metadata sent by the app.
create or replace function private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, display_name)
  values (new.id, nullif(btrim(new.raw_user_meta_data ->> 'display_name'), ''))
  on conflict (id) do nothing;
  return new;
end;
$$;

create trigger on_auth_user_created
after insert on auth.users
for each row execute function private.handle_new_user();

