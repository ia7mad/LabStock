-- =====================================================================
-- LabStock - production schema reference
-- ---------------------------------------------------------------------
-- The LIVE Supabase project is the source of truth. This file mirrors it
-- so the repository documents the real schema. It is NOT run by the app
-- and MUST NOT be applied to the live project.
--
-- Live tables: profiles, groups, items, batches, scan_aliases,
--              stock_movements, inventory_sessions, inventory_counts.
-- Live RPCs:   apply_stock_delta, complete_inventory_session.
--
-- Stock rule: the client never writes batches.current_quantity directly.
-- Insert a batch with current_quantity = 0, then call apply_stock_delta.
-- =====================================================================

create extension if not exists pgcrypto;
create schema if not exists private;

-- profiles -------------------------------------------------------------
-- One row per auth user; created automatically by the backend on signup.
create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  display_name text,
  expiry_warning_days integer not null default 30,
  notifications_enabled boolean not null default false,
  created_at timestamptz not null default now()
);

-- groups ---------------------------------------------------------------
create table if not exists public.groups (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  created_at timestamptz not null default now(),
  created_by uuid not null references auth.users (id)
);

-- items ----------------------------------------------------------------
create table if not exists public.items (
  id uuid primary key default gen_random_uuid(),
  group_id uuid references public.groups (id) on delete set null,
  name text not null,
  manufacturer text,
  reference_number text,
  notes text,
  low_stock_threshold integer not null default 1,
  unit_name text not null default 'unit',
  created_at timestamptz not null default now(),
  created_by uuid not null references auth.users (id)
);

-- batches --------------------------------------------------------------
create table if not exists public.batches (
  id uuid primary key default gen_random_uuid(),
  item_id uuid not null references public.items (id) on delete cascade,
  lot_number text,
  expiry_date date,
  current_quantity integer not null default 0,
  created_at timestamptz not null default now(),
  created_by uuid not null references auth.users (id)
);

-- scan_aliases ---------------------------------------------------------
-- normalized_value is generated by the database (lower + trimmed).
create table if not exists public.scan_aliases (
  id uuid primary key default gen_random_uuid(),
  item_id uuid not null references public.items (id) on delete cascade,
  type text not null check (type in ('barcode', 'ref', 'text')),
  value text not null,
  normalized_value text generated always as (lower(btrim(value))) stored,
  created_at timestamptz not null default now(),
  created_by uuid not null references auth.users (id)
);

-- stock_movements ------------------------------------------------------
-- Written only by apply_stock_delta; snapshots keep history readable even
-- after a batch is edited or deleted.
create table if not exists public.stock_movements (
  id uuid primary key default gen_random_uuid(),
  item_id uuid not null references public.items (id) on delete restrict,
  batch_id uuid references public.batches (id) on delete set null,
  type text not null check (type in ('add', 'withdraw', 'adjustment', 'inventory')),
  quantity_delta integer not null,
  quantity_before integer not null,
  quantity_after integer not null,
  note text,
  lot_number_snapshot text,
  expiry_date_snapshot date,
  user_id uuid not null references auth.users (id),
  created_at timestamptz not null default now()
);

-- inventory_sessions ---------------------------------------------------
create table if not exists public.inventory_sessions (
  id uuid primary key default gen_random_uuid(),
  group_id uuid references public.groups (id) on delete set null,
  status text not null default 'active' check (status in ('active', 'completed')),
  started_by uuid not null references auth.users (id),
  started_at timestamptz not null default now(),
  completed_at timestamptz
);

-- inventory_counts -----------------------------------------------------
-- For v1 every count is tied to a specific batch (batch_id not null in practice).
create table if not exists public.inventory_counts (
  id uuid primary key default gen_random_uuid(),
  session_id uuid not null references public.inventory_sessions (id) on delete cascade,
  item_id uuid not null references public.items (id) on delete cascade,
  batch_id uuid references public.batches (id) on delete cascade,
  expected_quantity integer not null,
  counted_quantity integer not null default 0,
  created_at timestamptz not null default now()
);

create index if not exists batches_item_id_idx on public.batches (item_id);
create index if not exists items_group_id_idx on public.items (group_id);
create index if not exists scan_aliases_lookup_idx on public.scan_aliases (normalized_value);
create index if not exists stock_movements_created_at_idx on public.stock_movements (created_at desc);
create index if not exists inventory_counts_session_idx on public.inventory_counts (session_id);

